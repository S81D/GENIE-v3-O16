  TOPVOLFLG="-t $TOPVOL"
fi
if [ -n "$ZMIN" ]; then
  ZMINFLG="-z $ZMIN" #  eg. -z -2000"  # start at z = -20m
fi
if [ -n "$FIDCUT" ]; then
  # fiducial volume cut ... 2.8.6 doesn't have rock box??? 2.9.0 doesn't either!
