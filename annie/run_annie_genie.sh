     $EXE -r $RUN $SEEDFLG $TOPVOLFLG -f $FLUX -g $GDML $UNITS $XSEC $GENFLG $MAXPL $LIMIT $MSGLVL $FIDFLG $ZMINFLG $TUNEFLG > gntp.${RUN}.ghep.log 2>&1
